#!/usr/bin/env bash
set -euo pipefail

SPEC_FILE=$1
SPOTIFY_VERSION=$2
MINIMUM_GLIBC=${3:-2.39}
[[ "$MINIMUM_GLIBC" =~ ^[0-9]+([.][0-9]+)*$ ]] || { echo 'Invalid glibc minimum' >&2; exit 2; }


PRIVATE_CODEC_REQUIRES=""
if [[ "$BUILTIN_FFMPEG" =~ ^(1|true|True|y|Y)$ ]]; then
    PRIVATE_CODEC_REQUIRES="|libavcodec|libavformat|libavutil|libswresample|libswscale"
    RECOMMENDS_FFMPEG1=""
    RECOMMENDS_FFMPEG2=""
else
    RECOMMENDS_FFMPEG1="Recommends:       (libavcodec.so.61()(64bit) or libavcodec.so.60()(64bit) or libavcodec.so.58()(64bit))"
    RECOMMENDS_FFMPEG2="Recommends:       (libavformat.so.61()(64bit) or libavformat.so.60()(64bit) or libavformat.so.58()(64bit))"
fi

cat > "${SPEC_FILE}" <<SPEC
%global debug_package %{nil}
%global __strip /bin/true
%global __brp_strip /bin/true
# Private bundled libraries must not satisfy other RPM packages' dependencies.
%global __provides_exclude_from ^%{_datadir}/spotify/.*$
%global __requires_exclude ^(libcef|libEGL|libGLESv2|libvk_swiftshader|libvulkan${PRIVATE_CODEC_REQUIRES})[.]so.*$

Name:           spotify
Version:        ${SPOTIFY_VERSION}
Release:        3%{?dist}
Summary:        Spotify desktop client
License:        Proprietary
URL:            https://www.spotify.com/
ExclusiveArch:  x86_64 x86_64_v2
Source0:        spotify-client-%{version}.tar.gz
Provides:       spotify-client = %{version}-%{release}
Obsoletes:      spotify-client < %{version}-%{release}
Conflicts:      spotify-client > %{version}-%{release}

BuildRequires:  tar
BuildRequires:  bash
BuildRequires:  gzip


Requires:       bash
Requires:       coreutils
Requires:       glibc >= ${MINIMUM_GLIBC}
Requires:       xdg-utils
# ELF requirements are generated by RPM using sonames and symbol versions.
# These capabilities work across Fedora, EL, Mageia, openEuler and openSUSE.
Requires:       libayatana-appindicator3.so.1()(64bit)


$RECOMMENDS_FFMPEG1
$RECOMMENDS_FFMPEG2

Suggests:       libnotify


%description
Spotify streaming music client.


%prep
%setup -q -n spotify-client-%{version}

%install
mkdir -p %{buildroot}/
cp -ar * %{buildroot}/
# Normalize vendor modes; only root may modify installed application files.
find %{buildroot}/usr/share/spotify -type d -exec chmod 0755 {} +
find %{buildroot}/usr/share/spotify -type f -exec chmod go-w {} +
find %{buildroot}/usr/share/spotify -type f -name '*.so*' -exec chmod 0755 {} +
chmod +x %{buildroot}/usr/share/spotify/generate_flags_file.sh
chmod +x %{buildroot}/usr/share/spotify/generate_envs_file.sh
chmod +x %{buildroot}/usr/bin/spotify

%files
%defattr(-,root,root,-)
%{_bindir}/spotify
%{_datadir}/spotify/
%{_datadir}/applications/spotify.desktop
%{_datadir}/icons/hicolor/scalable/apps/spotify-client.svg
%{_datadir}/icons/hicolor/*/apps/spotify-client.png
%{_datadir}/appdata/spotify.appdata.xml
%{_mandir}/man1/spotify.1*

%changelog
* $(date +"%a %b %d %Y") Automated Build <${GPG_EMAIL:-builder@localhost}> - ${SPOTIFY_VERSION}-3
- Automated build of Spotify client ${SPOTIFY_VERSION}
SPEC
